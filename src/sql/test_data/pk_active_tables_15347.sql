SELECT
    a.table_nm,
    CASE WHEN i.object_id IS NULL THEN 0 ELSE 1 END AS has_pk,
    COALESCE(
        STRING_AGG(c.name, N',') WITHIN GROUP (ORDER BY ic.key_ordinal),
        N''
    ) AS pk_cols,
    COUNT(c.name) AS key_count
FROM #active AS a
LEFT JOIN sys.tables AS t
    ON t.name = a.table_nm
   AND t.schema_id = SCHEMA_ID(N'dbo')
LEFT JOIN sys.indexes AS i
    ON i.object_id = t.object_id
   AND i.is_primary_key = 1
LEFT JOIN sys.index_columns AS ic
    ON ic.object_id = i.object_id
   AND ic.index_id = i.index_id
LEFT JOIN sys.columns AS c
    ON c.object_id = ic.object_id
   AND c.column_id = ic.column_id
GROUP BY a.table_nm, i.object_id
ORDER BY has_pk, a.table_nm;
